<?php
/* ============================================================
   Лабораторная работа №5
   Тема: Динамическое формирование контента и меню.
   Таблица умножения.

   В работе используются два GET-параметра:
   html_type — отвечает за тип верстки: TABLE или DIV.
   content — отвечает за содержание: вся таблица или таблица на число.
   ============================================================ */


/* ---------- Функция преобразования числа в ссылку ---------- */

// Функция получает число и возвращает его как ссылку,
// если это число от 2 до 9.
// По требованию лабораторной все цифры в таблице должны быть ссылками.
function outNumAsLink($x) {

    // Если число находится в диапазоне таблицы умножения от 2 до 9,
    // то делаем его ссылкой на соответствующую таблицу умножения.
    if ($x >= 2 && $x <= 9) {
        return '<a href="?content=' . $x . '">' . $x . '</a>';
    }

    // Если число больше 9, например результат 15, 24, 36,
    // оно не должно становиться ссылкой на таблицу, потому что таких пунктов меню нет.
    return $x;
}


/* ---------- Функция вывода одного столбца таблицы умножения ---------- */

// Функция outRow() выводит таблицу умножения на одно число.
// Например, если $n = 4, будет выведено:
// 4 x 2 = 8
// 4 x 3 = 12
// ...
// 4 x 9 = 36
function outRow($n) {

    // Цикл от 2 до 9, потому что в лабораторной таблица умножения строится для чисел 2–9.
    for ($i = 2; $i <= 9; $i++) {

        // Вычисляем результат умножения.
        $result = $n * $i;

        // Выводим строку таблицы умножения.
        // Числа превращаются в ссылки через функцию outNumAsLink().
        // Ссылки из самой таблицы сбрасывают тип верстки, потому что передают только content.
        echo outNumAsLink($n) . ' x ' . outNumAsLink($i) . ' = ' . outNumAsLink($result) . '<br>';
    }
}


/* ---------- Функция вывода таблицы умножения табличной версткой ---------- */

// Функция outTableForm() выводит таблицу умножения через HTML-теги <table>, <tr>, <td>.
function outTableForm() {

    // Если параметр content не передан,
    // значит нужно вывести всю таблицу умножения.
    if (!isset($_GET['content'])) {

        // Начинаем HTML-таблицу и первую строку.
        echo '<table><tr>';

        // Вся таблица состоит из восьми столбцов: от 2 до 9.
        for ($i = 2; $i <= 9; $i++) {

            // Открываем ячейку таблицы.
            echo '<td>';

            // Внутри ячейки выводим столбец умножения на текущее число.
            outRow($i);

            // Закрываем ячейку таблицы.
            echo '</td>';
        }

        // Закрываем строку и таблицу.
        echo '</tr></table>';
    }

    // Если параметр content передан,
    // значит нужно вывести только одну таблицу умножения на выбранное число.
    else {

        // Открываем таблицу с классом bigTable, чтобы выбранный столбец был крупнее.
        echo '<table class="bigTable"><tr><td>';

        // Выводим столбец умножения на число из GET-параметра content.
        outRow($_GET['content']);

        // Закрываем ячейку, строку и таблицу.
        echo '</td></tr></table>';
    }
}


/* ---------- Функция вывода таблицы умножения блочной версткой ---------- */

// Функция outDivForm() выводит таблицу умножения через блоки <div>.
function outDivForm() {

    // Если параметр content не передан,
    // выводим всю таблицу умножения в виде отдельных блоков.
    if (!isset($_GET['content'])) {

        // Цикл создаёт восемь блоков: на 2, 3, 4 ... 9.
        for ($i = 2; $i <= 9; $i++) {

            // Открываем блок одного столбца таблицы умножения.
            echo '<div class="ttRow">';

            // Выводим столбец умножения на текущее число.
            outRow($i);

            // Закрываем блок.
            echo '</div>';
        }
    }

    // Если параметр content передан,
    // выводим только один выбранный столбец.
    else {

        // Открываем крупный блок для выбранной таблицы умножения.
        echo '<div class="ttSingleRow">';

        // Выводим таблицу умножения на выбранное число.
        outRow($_GET['content']);

        // Закрываем блок.
        echo '</div>';
    }
}
