<?php
/* ===================================
   В структуре таблицы:
   * — разделяет ячейки одной строки;
   # — разделяет строки таблицы.
   ==================================== */


//количество колонок, если значений меньше - программа добавит пустые ячейки до нужного кол-ва колонок

$cols = 3;


// Структуры будущих таблиц.
// Каждый элемент массива — это отдельная таблица.
// "A*B*C#D*E*F"
// первая строка таблицы: A, B, C
// вторая строка таблицы: D, E, F

$tables = array(
    "A*B*C#D*E*F",
    "1*2*3#4*5*6",
    "X*Y*Z",
    "PHP*HTML*CSS#JS*SQL",
    "a*b*c#d*e",
    "q*w*e#r*t*y",
    "11*22*33",
    "яблоко*груша*слива",
    "red*green*blue",
    "one*two*three#four*five*six"
);


/* ---------- Функция формирования строки таблицы ---------- */

// Функция getTR() получает одну строку таблицы
// и превращает ее в HTML-код вида:
// <tr><td>...</td><td>...</td><td>...</td></tr>
//
// $data — строка с ячейками, разделенными символом *
// $cols — нужное количество колонок в таблице

function getTR($data, $cols) {

    // Если строка пустая, значит в ней нет ячеек.
    // По условию лабораторной работы такая строка не должна выводиться.

    if ($data == '') {
        return '';
    }

    // Разбиваем строку на отдельные ячейки.
    // Например, строка "A*B*C" превратится в массив:
    // ["A", "B", "C"]

    $cells = explode('*', $data);

    // Начинаем собирать HTML-код строки таблицы.

    $row = "<tr>";

    // Цикл идет от 0 до количества колонок.
    // Благодаря этому в каждой строке будет ровно $cols ячеек.

    for ($i = 0; $i < $cols; $i++) {

        // Если в массиве $cells есть значение с таким номером,
        // добавляем его в ячейку таблицы <td>.

        if ($i < count($cells)) {
            $row .= "<td>{$cells[$i]}</td>";
        }

        // Если значений меньше, чем колонок,
        // добавляем пустую ячейку.
        // Например, при $cols = 3 строка "JS*SQL"
        // станет строкой из трех ячеек: JS | SQL | пусто.

        else {
            $row .= "<td></td>";
        }
    }

    // Закрываем тег строки </tr>
    return $row . "</tr>";
}


/* ---------- Функция вывода полной таблицы ---------- */

// Функция outTable() получает структуру таблицы,
// обрабатывает ее и выводит готовую HTML-таблицу.
//
// $structure — структура таблицы в строковом виде
// $cols — количество колонок
// $num — номер таблицы для заголовка "Таблица №..."
function outTable($structure, $cols, $num) {

    // Проверяем количество колонок.
    // Если $cols равен 0, таблицы выводить нельзя.
    // По требованию лабораторной работы выводится сообщение об ошибке.
    if ($cols == 0) {
        echo "Неправильное число колонок<br>";
        return;
    }
 
    // Если вся структура таблицы пустая,
    // значит в ней вообще нет строк.
    // В этом случае таблица не выводится.
    if ($structure == '') {
        echo "В таблице нет строк<br>";
        return;
    }

    // Разбиваем структуру таблицы на отдельные строки.
    // Разделителем строк является символ #.
    // Например:
    // "A*B*C#D*E*F"
    // превратится в:
    // ["A*B*C", "D*E*F"]

    $rows = explode('#', $structure);

    // В эту переменную будут постепенно добавляться
    // все сформированные строки таблицы.

    $tableHTML = "";

    // Проходим по каждой строке структуры таблицы.
    foreach ($rows as $row) {

        // Для каждой строки вызываем функцию getTR().
        // Она возвращает HTML-код одной строки таблицы.
        $tr = getTR($row, $cols);

        // Если строка не пустая, добавляем ее к таблице.
        // Пустые строки пропускаются.
        if ($tr != '') {
            $tableHTML .= $tr;
        }
    }

    // Если после обработки строк таблица осталась пустой,
    // значит в структуре не было строк с ячейками.
    // По условию выводится соответствующее сообщение.

    if ($tableHTML == "") {
        echo "В таблице нет строк с ячейками<br>";
        return;
    }

    // Перед каждой таблицей обязательно выводится заголовок <h2>.
    // Номер таблицы передается в функцию через переменную $num.

    echo "<h2>Таблица №{$num}</h2>";

    // Выводим саму таблицу.
    // border='1' нужен, чтобы границы таблицы были видны на странице.

    echo "<table border='1'>{$tableHTML}</table>";
}


/* ---------- Основной цикл программы ---------- */

// Перебираем все элементы массива $tables.
// Каждый элемент массива — это структура одной отдельной таблицы.
for ($i = 0; $i < count($tables); $i++) {

    // Вызываем функцию outTable() для каждой таблицы.
    //
    // $tables[$i] — текущая структура таблицы;
    // $cols — количество колонок;
    // $i + 1 — номер таблицы.
    //
    // Используется $i + 1, потому что индексы массива начинаются с 0,
    // а номера таблиц на странице должны начинаться с 1.
    
    outTable($tables[$i], $cols, $i + 1);
}
?>