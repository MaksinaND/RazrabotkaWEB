<div id="main_menu">
    <?php
    // Начинаем формировать ссылку на табличную верстку.
    echo '<a href="?html_type=TABLE';

    // Если сейчас выбран конкретный столбец таблицы,
    // добавляем параметр content, чтобы при смене верстки содержание не сбрасывалось.
    if (isset($_GET['content'])) {
        echo '&content=' . $_GET['content'];
    }

    // Закрываем адрес ссылки.
    echo '"';

    // Если пользователь выбрал табличную верстку,
    // добавляем класс selected для выделения пункта меню.
    if (isset($_GET['html_type']) && $_GET['html_type'] == 'TABLE') {
        echo ' class="selected"';
    }

    // Выводим текст ссылки.
    echo '>Табличная верстка</a>';


    // Начинаем формировать ссылку на блочную верстку.
    echo '<a href="?html_type=DIV';

    // Если выбран конкретный столбец таблицы,
    // сохраняем параметр content и при смене верстки.
    if (isset($_GET['content'])) {
        echo '&content=' . $_GET['content'];
    }

    // Закрываем адрес ссылки.
    echo '"';

    // Если пользователь выбрал блочную верстку,
    // добавляем класс selected для выделения пункта меню.
    if (isset($_GET['html_type']) && $_GET['html_type'] == 'DIV') {
        echo ' class="selected"';
    }

    // Выводим текст ссылки.
    echo '>Блочная верстка</a>';
    ?>
