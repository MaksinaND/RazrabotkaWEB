<div id="wrapper">

    <!-- Левое меню -->
    <div id="side_menu">
        <?php
        // Переменная $link хранит начало ссылки для левого меню.
        // Она нужна, чтобы при выборе содержания сохранялся текущий тип верстки.
        $link = '?';

        // Если выбран тип верстки, добавляем его в ссылки левого меню.
        if (isset($_GET['html_type'])) {
            $link = '?html_type=' . $_GET['html_type'] . '&';
        }

        // Ссылка "Всё" выводит всю таблицу умножения.
        echo '<a href="' . $link . '"';

        // Если content не задан, значит сейчас выбрана вся таблица,
        // поэтому пункт "Всё" выделяется.
        if (!isset($_GET['content'])) {
            echo ' class="selected"';
        }

        // Завершаем ссылку "Всё".
        echo '>Всё</a>';


        // Цикл создаёт пункты меню с числами от 2 до 9.
        for ($i = 2; $i <= 9; $i++) {

            // Формируем ссылку на таблицу умножения на число $i.
            echo '<a href="' . $link . 'content=' . $i . '"';

            // Если content равен текущему числу,
            // значит этот пункт меню выбран и должен быть выделен.
            if (isset($_GET['content']) && $_GET['content'] == $i) {
                echo ' class="selected"';
            }

            // В тексте ссылки выводим только число, как требуется в задании.
            echo '>' . $i . '</a>';
        }
        ?>
    </div>


    <!-- Блок с таблицей умножения -->
    <div id="content">
        <?php
        // Если параметр html_type не передан,
        // по умолчанию используется табличная верстка.
        //
        // Если html_type равен TABLE,
        // также выводится табличная верстка.
        if (!isset($_GET['html_type']) || $_GET['html_type'] == 'TABLE') {
            outTableForm();
        }

        // Во всех остальных случаях выводится блочная верстка.
        else {
            outDivForm();
        }
        ?>
    </div>

