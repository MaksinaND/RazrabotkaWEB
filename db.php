<?php
/* ============================================================
   Модуль db.php
   Здесь хранятся настройки подключения к базе данных и функция
   connectDB(), которая используется во всех остальных модулях.

   Перед запуском нужно создать базу данных и таблицу contacts.
   SQL-код есть в файле init.sql.
   ============================================================ */

// Адрес сервера базы данных. Для локального сервера обычно localhost.
define('DB_HOST', 'localhost');

// Имя пользователя MySQL. В XAMPP часто используется root.
define('DB_USER', 'root');

// Пароль пользователя MySQL. В XAMPP по умолчанию часто пустой.
define('DB_PASS', '');

// Имя базы данных для записной книжки.
define('DB_NAME', 'notebook_lab9');

// Функция подключается к MySQL и возвращает объект подключения.
function connectDB() {
    // Создаем подключение к серверу MySQL и выбранной базе.
    $mysqli = mysqli_connect(DB_HOST, DB_USER, DB_PASS, DB_NAME);

    // Если подключение не получилось, останавливаем программу.
    if (!$mysqli) {
        die('Ошибка подключения к БД: ' . mysqli_connect_error());
    }

    // Устанавливаем UTF-8, чтобы русский текст нормально сохранялся и выводился.
    mysqli_set_charset($mysqli, 'utf8mb4');

    // Возвращаем подключение, чтобы другие модули могли выполнять SQL-запросы.
    return $mysqli;
}

// Функция безопасно выводит данные в HTML.
function h($value) {
    return htmlspecialchars((string)$value, ENT_QUOTES, 'UTF-8');
}
