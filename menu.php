<?php
/* ============================================================
   Модуль menu.php
   Содержит функцию getMenu().
   Она возвращает HTML-код главного меню сайта.
   ============================================================ */

function getMenu() {
    // Если параметр p не передан, по умолчанию открываем просмотр.
    $page = $_GET['p'] ?? 'viewer';

    // Разрешенные страницы. Это защита от случайных неправильных параметров.
    $allowedPages = array('viewer', 'add', 'edit', 'delete');

    // Если пользователь вручную ввел неправильный параметр, возвращаемся к просмотру.
    if (!in_array($page, $allowedPages)) {
        $page = 'viewer';
    }

    // Начинаем формировать HTML-код меню.
    $html = '<div id="menu">';

    // Массив пунктов главного меню: параметр => текст ссылки.
    $items = array(
        'viewer' => 'Просмотр',
        'add'    => 'Добавление записи',
        'edit'   => 'Редактирование записи',
        'delete' => 'Удаление записи'
    );

    // Перебираем пункты меню и формируем ссылки.
    foreach ($items as $key => $title) {
        // Если пункт совпадает с текущей страницей, добавляем класс selected.
        $class = ($page == $key) ? ' class="selected"' : '';
        $html .= '<a href="?p=' . $key . '"' . $class . '>' . $title . '</a>';
    }

    // Подменю сортировки показывается только при просмотре записей.
    if ($page == 'viewer') {
        // Текущий тип сортировки. По умолчанию сортировка по порядку добавления.
        $sort = $_GET['sort'] ?? 'byid';

        // Разрешенные виды сортировки.
        $allowedSorts = array('byid', 'surname', 'birth');
        if (!in_array($sort, $allowedSorts)) {
            $sort = 'byid';
        }

        // Пункты подменю сортировки.
        $sortItems = array(
            'byid'    => 'По порядку добавления',
            'surname' => 'По фамилии',
            'birth'   => 'По дате рождения'
        );

        $html .= '<div id="submenu">';

        // Формируем ссылки подменю.
        foreach ($sortItems as $key => $title) {
            $class = ($sort == $key) ? ' class="selected"' : '';
            $html .= '<a href="?p=viewer&sort=' . $key . '"' . $class . '>' . $title . '</a>';
        }

        $html .= '</div>';
    }

    $html .= '</div>';

    // Возвращаем готовый HTML-код меню.
    return $html;
}
?>
